// --------------------------------------------------
// Generate slug
// --------------------------------------------------

export function getOpportunitySlug(item) {
    return (
        item.slug ||
        item.title
            .toLowerCase()
            .trim()
            .replace(/[^\w\s-]/g, "")
            .replace(/\s+/g, "-")
            .replace(/-+/g, "-")
    );
}

// --------------------------------------------------
// Check whether opportunity is open
// --------------------------------------------------

export function isOpportunityOpen(item) {
    const today = new Date();
    const deadline = new Date(item.deadline);

    // Set deadline to the end of the day
    deadline.setHours(23, 59, 59, 999);

    return deadline >= today;
}